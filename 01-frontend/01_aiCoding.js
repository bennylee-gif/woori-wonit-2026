// 두 수를 더하는 함수를 작성해줘.
// 변경할 영역을 드래그하여 선택한 뒤, ctrl+I로 수정창을 열어서 수정 가능
function add(a, b) {
    return a + b;
}   

// 두 수를 빼는 함수
// tab으로 선택, esc로 자동완성 취소
function subtractNumbers(a, b) {
    return a - b;
}   

